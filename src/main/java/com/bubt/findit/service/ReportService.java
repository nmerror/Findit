package com.bubt.findit.service;

import com.bubt.findit.core.model.DashboardStats;
import com.bubt.findit.core.registry.ServiceRegistry;
import com.bubt.findit.core.spi.AdminWorkloadService;
import com.bubt.findit.core.spi.AuditService;
import com.bubt.findit.core.spi.ClaimQueryService;
import com.bubt.findit.core.spi.ItemCatalogService;
import com.bubt.findit.core.spi.MatchQueryService;
import com.bubt.findit.core.model.ItemSummary;
import com.bubt.findit.core.model.LocationCount;
import com.bubt.findit.core.model.User;
import com.bubt.findit.db.dao.AuditEntry;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.List;

/**
 * ============================================================================
 *  SEGMENT 1 - Report Generation Service
 * ============================================================================
 *
 * <p>Builds the "Search and Report Generation" feature of the project
 * proposal (Section 6) and the JOIN / REPORT database operation of
 * Section 9.
 *
 * <p>Segment 1 reports the data it owns ({@code users}, {@code audit_log})
 * and the counters that the other segments publish through their contracts.
 * The report therefore grows automatically as the other segments arrive.
 */
public class ReportService {

    private static final DateTimeFormatter STAMP = DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm");
    private static final DateTimeFormatter FILE_STAMP = DateTimeFormatter.ofPattern("yyyyMMdd-HHmmss");

    private final AuditService auditService;

    public ReportService(AuditService auditService) {
        this.auditService = auditService;
    }

    /** A human-readable report of the whole system. */
    public String buildTextReport(User viewer, DashboardStats stats, List<AuditEntry> recentAudit) {
        StringBuilder out = new StringBuilder();

        out.append("FINDIT - CAMPUS LOST & FOUND SYSTEM\n");
        out.append("=========================================================\n");
        out.append("Generated      : ").append(LocalDateTime.now().format(STAMP)).append('\n');
        out.append("Generated by   : ").append(viewer == null ? "system"
                : viewer.getFullName() + " (" + viewer.getRole().label() + ")").append('\n');
        out.append("Scope          : whole system\n");
        out.append('\n');

        appendSegmentStatus(out);
        out.append("1. ACCOUNTS  (Segment 1)\n");
        out.append("---------------------------------------------------------\n");
        out.append(row("Registered users", stats.getTotalUsers())).append('\n');
        out.append(row("  students", stats.getTotalStudents())).append('\n');
        out.append(row("  administrators", stats.getTotalAdmins())).append('\n');
        out.append(row("Active accounts", stats.getActiveUsers())).append('\n');
        out.append(row("Suspended accounts", stats.getSuspendedUsers())).append('\n');
        out.append('\n');

        out.append("2. LOST & FOUND ITEMS  (Segment 2)\n");
        out.append("---------------------------------------------------------\n");
        out.append(row("Lost items reported", stats.getTotalLostItems())).append('\n');
        out.append(row("Found items reported", stats.getTotalFoundItems())).append('\n');
        out.append(row("Items still open", stats.getTotalLostItems() + stats.getTotalFoundItems())).append('\n');
        List<LocationCount> locations = stats.getTopLocations();
        if (locations != null && !locations.isEmpty()) {
            out.append("Busiest locations:\n");
            for (LocationCount location : locations) {
                out.append("   - ").append(pad(location.getLabel(), 34))
                        .append(location.getCount()).append(" items\n");
            }
        } else {
            out.append("Busiest locations     : no data yet (Segment 2 pending)\n");
        }
        out.append('\n');

        out.append("3. CLAIM PIPELINE  (Segment 3 & 4)\n");
        out.append("---------------------------------------------------------\n");
        out.append(row("Open claims", stats.getOpenClaims())).append('\n');
        out.append(row("Pending verification", stats.getPendingVerification())).append('\n');
        out.append(row("Approved claims", stats.getApprovedClaims())).append('\n');
        out.append(row("Items returned", stats.getReturnedItems())).append('\n');
        out.append('\n');

        out.append("4. MATCHING ENGINE  (Segment 3)\n");
        out.append("---------------------------------------------------------\n");
        out.append(row("New matches waiting", stats.getNewMatches())).append('\n');
        out.append('\n');

        out.append("5. RECENTLY REPORTED ITEMS\n");
        out.append("---------------------------------------------------------\n");
        List<ItemSummary> items = stats.getRecentItems();
        if (items != null && !items.isEmpty()) {
            for (ItemSummary item : items) {
                out.append("   - ").append(pad(item.getTitle(), 30))
                        .append(pad(item.getType() == null ? "" : item.getType().label(), 12))
                        .append(pad(item.getLocationLabel(), 20))
                        .append(item.getPostedByName() == null ? "" : item.getPostedByName())
                        .append('\n');
            }
        } else {
            out.append("   no items reported yet\n");
        }
        out.append('\n');

        out.append("6. RECENT ACTIVITY  (audit trail)\n");
        out.append("---------------------------------------------------------\n");
        if (recentAudit != null && !recentAudit.isEmpty()) {
            for (AuditEntry entry : recentAudit) {
                out.append("   - ")
                        .append(pad(entry.getCreatedAt() == null ? "" : entry.getCreatedAt().format(STAMP), 20))
                        .append(pad(entry.getAction(), 18))
                        .append(entry.getDetails() == null ? "" : entry.getDetails())
                        .append('\n');
            }
        } else {
            out.append("   no activity recorded yet\n");
        }

        out.append('\n');
        out.append("=========================================================\n");
        out.append("End of report\n");
        return out.toString();
    }

    /** The same numbers as a CSV file, for a spreadsheet or a report appendix. */
    public String buildCsvReport(User viewer, DashboardStats stats) {
        StringBuilder out = new StringBuilder();
        out.append("section,metric,value\n");
        out.append("accounts,registered users,").append(stats.getTotalUsers()).append('\n');
        out.append("accounts,students,").append(stats.getTotalStudents()).append('\n');
        out.append("accounts,administrators,").append(stats.getTotalAdmins()).append('\n');
        out.append("accounts,active,").append(stats.getActiveUsers()).append('\n');
        out.append("accounts,suspended,").append(stats.getSuspendedUsers()).append('\n');
        out.append("items,lost,").append(stats.getTotalLostItems()).append('\n');
        out.append("items,found,").append(stats.getTotalFoundItems()).append('\n');
        out.append("claims,open,").append(stats.getOpenClaims()).append('\n');
        out.append("claims,pending verification,").append(stats.getPendingVerification()).append('\n');
        out.append("claims,approved,").append(stats.getApprovedClaims()).append('\n');
        out.append("claims,returned,").append(stats.getReturnedItems()).append('\n');
        out.append("matching,new matches,").append(stats.getNewMatches()).append('\n');
        List<LocationCount> locations = stats.getTopLocations();
        if (locations != null) {
            for (LocationCount location : locations) {
                out.append("locations,\"").append(location.getLabel().replace("\"", "'"))
                        .append("\",").append(location.getCount()).append('\n');
            }
        }
        out.append("report,generated at,").append(LocalDateTime.now().format(STAMP)).append('\n');
        out.append("report,generated by,").append(viewer == null ? "system" : viewer.getFullName())
                .append('\n');
        return out.toString();
    }

    /** A file name for the exported report. */
    public String suggestedFileName(String extension) {
        return "findit-report-" + LocalDateTime.now().format(FILE_STAMP) + "." + extension;
    }

    /** Writes the report to disk. Returns true when it worked. */
    public boolean exportTo(Path target, String content) {
        try {
            if (target.getParent() != null) {
                Files.createDirectories(target.getParent());
            }
            Files.writeString(target, content, StandardCharsets.UTF_8);
            return true;
        } catch (IOException ex) {
            System.err.println("[report] could not write " + target + ": " + ex.getMessage());
            return false;
        }
    }

    /** Records that a report was generated - the audit trail keeps track. */
    public void logExport(User viewer, String format) {
        if (auditService != null) {
            auditService.record("REPORT_EXPORT", viewer == null ? null : viewer.getId(),
                    "Generated a " + format + " report");
        }
    }

    /** A "label ....... value" line. */
    /**
     * Section 0 of the report: which segments are connected right now.
     *
     * <p>During the presentation this shows at a glance that the dashboard
     * really reads the other segments' tables.
     */
    private void appendSegmentStatus(StringBuilder out) {
        out.append("0. CONNECTED SEGMENTS\n");
        out.append("---------------------------------------------------------\n");
        out.append(row("Segment 1 - accounts & audit", "connected")).append('\n');
        out.append(row("Segment 2 - item catalog",
                describe(ServiceRegistry.get(ItemCatalogService.class)))).append('\n');
        out.append(row("Segment 3 - claims",
                describe(ServiceRegistry.get(ClaimQueryService.class)))).append('\n');
        out.append(row("Segment 3 - matching",
                describe(ServiceRegistry.get(MatchQueryService.class)))).append('\n');
        out.append(row("Segment 4 - verification",
                describe(ServiceRegistry.get(AdminWorkloadService.class)))).append('\n');
        out.append('\n');
    }

    /** "connected (database)", "connected (demo data)", "waiting (stub)" or "not connected". */
    private String describe(Object implementation) {
        if (implementation == null) {
            return "not connected";
        }
        String pkg = implementation.getClass().getPackageName();
        if (pkg.endsWith(".stub")) {
            return "waiting (stub)";
        }
        if (pkg.endsWith(".data")) {
            return "connected (database)";
        }
        return "connected (demo data)";
    }

    private String row(String label, int value) {
        return pad(label, 30) + value;
    }

    private String row(String label, String value) {
        return pad(label, 32) + value;
    }

    private String pad(String label, int width) {
        if (label == null) {
            label = "";
        }
        StringBuilder line = new StringBuilder(label);
        while (line.length() < width) {
            line.append(' ');
        }
        return line.toString();
    }
}
